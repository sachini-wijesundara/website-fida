// Generate dots on a 2D circular grid
const dots = [];
const gridW = 60;  // horizontal samples
const gridH = 60;  // vertical samples

for (let row = 0; row < gridH; row++) {
  for (let col = 0; col < gridW; col++) {
    // Normalise to -1..+1
    const nx = (col / (gridW - 1)) * 2 - 1;
    const ny = (row / (gridH - 1)) * 2 - 1;
    const r2 = nx * nx + ny * ny;
    if (r2 >= 0.96) continue; // outside the circular globe mask

    // Spherical projection: treat visible hemisphere as a sphere
    const nz = Math.sqrt(1 - r2);
    // Longitude on the visible hemisphere: -90° to +90°
    const lon = Math.atan2(nx, nz);   // -PI/2 .. +PI/2
    // Latitude: top is +lat, bottom is -lat  (ny is "up" if we negate)
    const lat = Math.asin(-ny);        // +PI/2 .. -PI/2

    // Map lon/lat → map pixel
    // Centre map at longitude ~20°E (showing Europe/Africa/Americas)
    const centreOffsetFrac = 0.31; // shift the visible centre
    let u = (lon / Math.PI + 1) / 2;  // 0..1 across visible hemisphere
    u = u * 0.5 + centreOffsetFrac;   // compress to half map + offset
    if (u < 0) u += 1;
    if (u > 1) u -= 1;

    const v = (lat / Math.PI + 0.5);  // 0(south)..1(north)

    const mapX = Math.floor(u * W);
    const mapY = Math.floor((1 - v) * H); // flip: row 0 = north

    if (mapY >= 0 && mapY < H && mapX >= 0 && mapX < W) {
      if (mapRows[mapY] && mapRows[mapY][mapX] === '#') {
        dots.push({
          left: (col / (gridW - 1)) * 100,
          top:  (row / (gridH - 1)) * 100,
        });
      }
    }
  }
}

fs.writeFileSync('dots.json', JSON.stringify(dots));
console.log(`Generated ${dots.length} Earth continent dots.`);

// Accurate 120x60 world map (1=land, 0=ocean)
// Latitude: 90N (top row) to 90S (bottom row)
// Longitude: 180W (left col) to 180E (right col)
const W = 120;
const H = 60;

// Each row is 120 chars. '#' = land, ' ' = ocean
